function isPlainObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

export function deepMergeLanguageCopy(base = {}, override = {}) {
  const output = { ...(isPlainObject(base) ? base : {}) };
  if (!isPlainObject(override)) return output;
  for (const [key, value] of Object.entries(override)) {
    if (isPlainObject(value) && isPlainObject(output[key])) {
      output[key] = deepMergeLanguageCopy(output[key], value);
    } else if (isPlainObject(value)) {
      output[key] = deepMergeLanguageCopy({}, value);
    } else {
      output[key] = value;
    }
  }
  return output;
}

export function getLanguageMetadata(code) {
  const normalized = String(code || "").trim().toLowerCase().replace(/_/g, "-");
  const exact = LANGUAGE_METADATA[normalized];
  if (exact) return exact;
  const base = normalized.split("-")[0];
  return LANGUAGE_METADATA[base] || null;
}

export function buildLocalizedCopy(legacyCopy = {}) {
  const english = deepMergeLanguageCopy(legacyCopy.en || {}, LANGUAGE_COMPONENT_COPY.en || {});
  const localized = { en: english };
  for (const code of REQUIRED_LANGUAGE_CODES) {
    if (code === "en") continue;
    localized[code] = deepMergeLanguageCopy(english, LANGUAGE_COMPONENT_COPY[code] || {});
  }
  return localized;
}
